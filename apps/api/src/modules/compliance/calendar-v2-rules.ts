function single(formLabel: string): SeedVersion[] {
  return [{ effectiveFrom: BASE_EFFECTIVE_FROM, formLabel }];
}

function gstMonthly(
  code: string,
  name: string,
  form: string,
  day: number,
  condition: unknown,
  section: PeriodSection,
  notes: string,
): SeedRule {
  return {
    code,
    name,
    notes,
    stream: 'gst',
    category: 'gst',
    dueDateCategory: 'STATUTORY_FIXED',
    registrationScope: 'gstin',
    frequency: 'monthly',
    section,
    basis: 'period_end',
    offsetDays: day,
    condition,
    lateFeeNote: GST_LATE_FEE,
    internalSlaOffsetDays: 3,
    versions: single(form),
  };
}

