/** A seed rule's version as the period engine sees it (for tests and the generator). */
export function seedVersion(
  rule: SeedRule,
  asOf: string,
): PeriodRuleVersion & { formLabel: string } {
  const v = [...rule.versions].reverse().find((x) => x.effectiveFrom <= asOf) ?? rule.versions[0]!;
  return {
    calculationBasis: rule.basis,
    frequency: rule.frequency,
    offsetMonths: rule.offsetMonths ?? 0,
    offsetDays: rule.offsetDays ?? 0,
    fixedMonth: null,
    fixedDay: null,
    workingDayAdjustment: 'none',
    internalSlaOffsetDays: rule.internalSlaOffsetDays,
    schedule: v.schedule ?? rule.schedule ?? null,
    periodOverrides: rule.periodOverrides ?? null,
    periodFilter: rule.periodFilter ?? null,
    provisionalEventRule: rule.provisionalEventRule ?? null,
    eventType: rule.eventType ?? null,
    formLabel: v.formLabel,
    section: rule.section ?? null,
    isOptional: rule.isOptional ?? false,
    condition: rule.condition ?? null,
    variants: rule.variants ?? null,
  };
}
