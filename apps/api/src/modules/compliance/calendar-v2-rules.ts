/**
 * The calendar v2 rule catalogue (spec Change 4): the 45 rows of the
 * Recurring Summary sheet (two for Form 3CEB / TP ITR) plus the 13 rows of its
 * Event-Based tab. This module is the single source: the seed migration
 * 1770100000000_calendar_v2_rules.sql is generated from it by
 * scripts/gen-calendar-v2-rules.ts, and the unit tests compute the spec's
 * dates from it, so the seeded encodings are the tested ones.
 *
 * Statutory dates are never shifted to a working day (working_day_adjustment
 * 'none', per the sheet's Read Me); relief comes only from
 * government_extensions. The internal date is pulled back to a working day.
 *
 * Conditions test the generation context built from the registration's
 * compliance profile (see buildRuleContext in compliance-generator.service.ts).
 */

export interface SeedVersion {
  effectiveFrom: string;
  formLabel: string;
  /** Replaces the rule's schedule for this version (e.g. TCS before the 2026 Rules). */
  schedule?: ScheduleEntry[];
  sourceRef?: string;
}

export interface SeedRule {
  code: string;
  name: string;
  /** The sheet's wording. */
  notes: string;
  stream: Stream;
  category: ComplianceCategory;
  dueDateCategory: DueDateCategory;
  registrationScope: RegistrationScope;
  frequency: RuleFrequency;
  section?: PeriodSection;
  basis: CalculationBasis;
  offsetMonths?: number;
  offsetDays?: number;
  schedule?: ScheduleEntry[];
  periodOverrides?: Record<string, PeriodOverride>;
  periodFilter?: string[];
  eventType?: string;
  provisionalEventRule?: ProvisionalEventRule;
  variants?: RuleVariant[];
  condition?: unknown;
  isOptional?: boolean;
  lateFeeNote?: string;
  verification?: RuleVerification;
  sourceRef?: string;
  internalSlaOffsetDays: number;
  /** Effective-dated versions, oldest first. Default: one version from 2017-04-01. */
  versions: SeedVersion[];
}

